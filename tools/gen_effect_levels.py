#!/usr/bin/env python3
"""Generate per-level copies of jutsu effects.

tools/effect_templates/<name>.efx is the level 2 version; this writes
assets/effects/shinobi/<name>_1.efx .. _3.efx with sizes, radii, particle
counts, speeds, light and camera shake scaled for each level.

Usage: python3 tools/gen_effect_levels.py
"""
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "effect_templates")
OUT = os.path.join(ROOT, "assets", "effects", "shinobi")

# per-template scale factors for levels 1, 2, 3 (match the gameplay radii in bg_shinobi.h)
FACTORS = {
    "rasengan_hit": (0.70, 1.0, 1.45),
    "chidori_hit": (0.75, 1.0, 1.35),
    "fireball_explode": (0.72, 1.0, 1.39),
}

NUM = re.compile(r"-?\d+(?:\.\d+)?")


def scale_numbers(text, factor, integer=False):
    def repl(m):
        v = float(m.group(0)) * factor
        if integer:
            return str(max(1, int(round(v))))
        return ("%.2f" % v).rstrip("0").rstrip(".")
    return NUM.sub(repl, text)


def scale_effect(src, f):
    out = []
    stack = []  # group names
    pending = None
    for line in src.splitlines():
        stripped = line.strip()
        if stripped == "{":
            stack.append(pending or "")
            out.append(line)
            continue
        if stripped == "}":
            if stack:
                stack.pop()
            out.append(line)
            continue
        m = re.match(r"(\s*)(\w+)(\s+)(.*)$", line)
        if not m or stripped.startswith("//"):
            pending = stripped if re.match(r"^\w+$", stripped) else None
            out.append(line)
            continue
        indent, key, gap, value = m.groups()
        pending = None
        group = stack[-1].lower() if stack else ""
        k = key.lower()
        if group == "size" and k in ("start", "end"):
            value = scale_numbers(value, f)
        elif k in ("radius", "intensity"):
            value = scale_numbers(value, f)
        elif k in ("vel", "velocity"):
            value = scale_numbers(value, math.sqrt(f))
        elif k == "count":
            value = scale_numbers(value, f, integer=True)
        out.append(indent + key + gap + value)
    return "\n".join(out) + "\n"


def main():
    for name, factors in FACTORS.items():
        with open(os.path.join(SRC, name + ".efx")) as fh:
            src = fh.read()
        for level, f in enumerate(factors, start=1):
            header = "// GENERATED by tools/gen_effect_levels.py from tools/effect_templates/%s.efx (level %d, x%.2f)\n" % (name, level, f)
            path = os.path.join(OUT, "%s_%d.efx" % (name, level))
            with open(path, "w") as fh:
                fh.write(header + scale_effect(src, f))
            print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
