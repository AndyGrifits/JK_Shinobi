#!/usr/bin/env python3
"""Generate the q3map2 game tree for a JK_Shinobi model-based map.

    python3 tools/maps/gen_map.py maps/<name>/map.json <build dir>

Needs <build>/model.obj, materials.json, textures/ (prep_model.py) and propclip.json (propclip.py).
Writes <build>/base/ (the -fs_basepath tree for q3map2 -game ja and the pk3 contents):
  maps/<name>.map                  caulk hull + prop clip + misc_model + lights + spawns
  models/map_objects/<name>/hall.obj   (compile-time only, not packed)
  shaders/<name>.shader            model shaders (+ q3map_clipModel / q3map_material) and tool shaders
  textures/<name>/*                 model textures
  scripts/<name>.arena             map list entry
"""
import json, os, shutil, sys

cfg_path, build = sys.argv[1:3]
cfg = json.load(open(cfg_path))
name = cfg["name"]; sd = cfg["shader_dir"]
base = os.path.join(build, "base")
for d in ("maps", f"models/map_objects/{name}", "shaders", "scripts", "textures"):
    os.makedirs(os.path.join(base, d), exist_ok=True)

# --- model + textures into the tree -------------------------------------------------------
mdl_rel = f"models/map_objects/{name}/hall.obj"
obj_src = open(os.path.join(build, "model.obj")).read().replace("mtllib model.mtl", "mtllib hall.mtl")
open(os.path.join(base, mdl_rel), "w").write(obj_src)
shutil.copy(os.path.join(build, "model.mtl"), os.path.join(base, f"models/map_objects/{name}/hall.mtl"))
tdst = os.path.join(base, "textures", sd)
if os.path.exists(tdst):
    shutil.rmtree(tdst)
shutil.copytree(os.path.join(build, "textures", sd), tdst)
materials = json.load(open(os.path.join(build, "materials.json")))

mn = [1e9] * 3; mx = [-1e9] * 3
for line in obj_src.splitlines():
    if line.startswith("v "):
        x, y, z = (float(v) for v in line.split()[1:4])
        p = [x, -z, y]   # OBJ Y-up -> game Z-up (what q3map2 does on load)
        mn = [min(a, b) for a, b in zip(mn, p)]; mx = [max(a, b) for a, b in zip(mx, p)]

# --- shaders --------------------------------------------------------------------------------
sh = [f"// {cfg['longname']} ({name}) - generated by tools/maps/gen_map.py, edit maps/{name}/map.json\n"]
for full, info in materials.items():
    short = full.split("/")[-1]
    c = cfg["shaders"].get(short, {})
    tex = os.path.splitext(info["file"])[0]
    lines = [full, "{", f"\tqer_editorimage {info['file']}", f"\t// {c.get('what', '')}"]
    if c.get("solid"):
        lines.append("\tq3map_clipModel")
    else:
        lines.append("\tsurfaceparm nonsolid")
    if c.get("mat"):
        lines.append(f"\tq3map_material {c['mat']}")
    lines += ["\tq3map_nonplanar", "\tq3map_shadeAngle 70"]
    if info["alpha"]:
        lines += ["\tsurfaceparm alphashadow", "\tsurfaceparm trans", "\tcull twosided",
                  "\t{", f"\t\tmap {tex}", "\t\talphaFunc GE128", "\t\tdepthWrite", "\t\trgbGen identity", "\t}",
                  "\t{", "\t\tmap $lightmap", "\t\tblendFunc GL_DST_COLOR GL_ZERO", "\t\tdepthFunc equal",
                  "\t\trgbGen identity", "\t}"]
    else:
        lines += ["\t{", "\t\tmap $lightmap", "\t\trgbGen identity", "\t}",
                  "\t{", f"\t\tmap {tex}", "\t\tblendFunc GL_DST_COLOR GL_ZERO", "\t\trgbGen identity", "\t}"]
    lines.append("}\n")
    sh.append("\n".join(lines))
tool = {
    "caulk": ["surfaceparm nodraw", "surfaceparm nolightmap", "surfaceparm nomarks"],
    "clip_rock": ["surfaceparm nodraw", "surfaceparm nolightmap", "surfaceparm trans", "surfaceparm nonopaque",
                  "q3map_material rock"],
    "clip_leaves": ["surfaceparm nodraw", "surfaceparm nolightmap", "surfaceparm trans", "surfaceparm nonopaque",
                    "q3map_material greenleaves"],
}
for t, parms in tool.items():
    sh.append("\n".join([f"textures/{sd}/{t}", "{", "\tqer_trans 0.4", *[f"\t{p}" for p in parms], "}\n"]))
open(os.path.join(base, "shaders", f"{name}.shader"), "w").write("\n".join(sh))

# --- .map ----------------------------------------------------------------------------------
def box(x0, y0, z0, x1, y1, z1, shader):
    s = f"{sd}/{shader} 0 0 0 0.5 0.5 0 0 0"   # .map faces name shaders without the textures/ prefix
    return "\n".join([
        "{",
        f"( {x0} 0 0 ) ( {x0} 1 0 ) ( {x0} 0 1 ) {s}",   # -X
        f"( {x1} 0 0 ) ( {x1} 0 1 ) ( {x1} 1 0 ) {s}",   # +X
        f"( 0 {y0} 0 ) ( 0 {y0} 1 ) ( 1 {y0} 0 ) {s}",   # -Y
        f"( 0 {y1} 0 ) ( 1 {y1} 0 ) ( 0 {y1} 1 ) {s}",   # +Y
        f"( 0 0 {z0} ) ( 1 0 {z0} ) ( 0 1 {z0} ) {s}",   # -Z
        f"( 0 0 {z1} ) ( 0 1 {z1} ) ( 1 0 {z1} ) {s}",   # +Z
        "}"])

def ent(kv, brushes=()):
    return "{\n" + "".join(f'"{k}" "{v}"\n' for k, v in kv.items()) + "".join(b + "\n" for b in brushes) + "}\n"

m = cfg.get("hull_margin", 32); t = 16
X0, Y0, Z0 = (int(v // 8 * 8) - m for v in mn)
X1, Y1, Z1 = (int(-(-v // 8) * 8) + m for v in mx)
hull = [box(X0 - t, Y0 - t, Z0 - t, X1 + t, Y1 + t, Z0, "caulk"), box(X0 - t, Y0 - t, Z1, X1 + t, Y1 + t, Z1 + t, "caulk"),
        box(X0 - t, Y0 - t, Z0, X0, Y1 + t, Z1, "caulk"), box(X1, Y0 - t, Z0, X1 + t, Y1 + t, Z1, "caulk"),
        box(X0, Y0 - t, Z0, X1, Y0, Z1, "caulk"), box(X0, Y1, Z0, X1, Y1 + t, Z1, "caulk")]
props = []
for g in json.load(open(os.path.join(build, "propclip.json"))):
    props += [box(*b, g["shader"]) for b in g["boxes"]]

ws = {"classname": "worldspawn", "message": cfg["longname"], **cfg.get("worldspawn", {})}
out = [ent(ws, hull + props)]
# spawnflags 4 = force meta: cut the model into lightmappable meta surfaces (JA: <= 64 verts each)
out.append(ent({"classname": "misc_model", "model": mdl_rel, "origin": "0 0 0", "spawnflags": "4", "_clipdepth": "8",
                "_castshadows": "1", "_receiveshadows": "1", "_lightmapscale": ws.get("_lightmapscale", "1")}))
L = cfg["lights"]
for x in L["grid_x"]:
    for y in L["grid_y"]:
        out.append(ent({"classname": "light", "origin": f"{x} {y} {L['z']}", "light": str(L["light"])}))
for e in L.get("extra", []):
    out.append(ent({"classname": "light", "origin": " ".join(map(str, e["origin"])), "light": str(e["light"])}))
for cls, pts in cfg["spawns"].items():
    if cls.startswith("_"):
        continue
    for x, y, z, yaw in pts:
        out.append(ent({"classname": cls, "origin": f"{x} {y} {z}", "angle": str(yaw)}))
open(os.path.join(base, "maps", f"{name}.map"), "w").write("// generated by tools/maps/gen_map.py\n" + "".join(out))

# --- arena ---------------------------------------------------------------------------------
open(os.path.join(base, "scripts", f"{name}.arena"), "w").write(
    "{\n" + f'map "{name}"\nlongname "{cfg["longname"]}"\ntype "{cfg["arena_type"]}"\n' + "}\n")

print(f"GEN OK {name}: hull {X0},{Y0},{Z0} .. {X1},{Y1},{Z1}; {len(props)} prop clip brushes; "
      f"{len(materials)} model shaders; {len(L['grid_x']) * len(L['grid_y']) + len(L.get('extra', []))} lights")
