#!/usr/bin/env python3
"""Generate the q3map2 game tree for a JK_Shinobi model-based map.

    python3 tools/maps/gen_map.py maps/<name>/map.json <build dir>

Needs <build>/model.obj, materials.json, textures/ (prep_model.py) and propclip.json (propclip.py).
Writes <build>/base/ (the -fs_basepath tree for q3map2 -game ja and the pk3 contents):
  maps/<name>.map                  caulk hull + prop clip + misc_model + lights + spawns
  models/map_objects/<name>/hall.obj   (compile-time only, not packed)
  shaders/<name>.shader            model shaders (+ q3map_clipModel / q3map_material) and tool shaders
  textures/<name>/*                 model textures
  scripts/<name>.arena             map list entry
"""
import json, os, shutil, sys

cfg_path, build = sys.argv[1:3]
cfg = json.load(open(cfg_path))
name = cfg["name"]; sd = cfg["shader_dir"]
base = os.path.join(build, "base")
for d in ("maps", f"models/map_objects/{name}", "shaders", "scripts", "textures"):
    os.makedirs(os.path.join(base, d), exist_ok=True)

# --- model + textures into the tree -------------------------------------------------------
mdl_rel = f"models/map_objects/{name}/hall.obj"
obj_src = open(os.path.join(build, "model.obj")).read().replace("mtllib model.mtl", "mtllib hall.mtl")
open(os.path.join(base, mdl_rel), "w").write(obj_src)
shutil.copy(os.path.join(build, "model.mtl"), os.path.join(base, f"models/map_objects/{name}/hall.mtl"))
tdst = os.path.join(base, "textures", sd)
if os.path.exists(tdst):
    shutil.rmtree(tdst)
shutil.copytree(os.path.join(build, "textures", sd), tdst)
materials = json.load(open(os.path.join(build, "materials.json")))

mn = [1e9] * 3; mx = [-1e9] * 3
for line in obj_src.splitlines():
    if line.startswith("v "):
        x, y, z = (float(v) for v in line.split()[1:4])
        p = [x, -z, y]   # OBJ Y-up -> game Z-up (what q3map2 does on load)
        mn = [min(a, b) for a, b in zip(mn, p)]; mx = [max(a, b) for a, b in zip(mx, p)]

# --- shaders --------------------------------------------------------------------------------
sh = [f"// {cfg['longname']} ({name}) - generated by tools/maps/gen_map.py, edit maps/{name}/map.json\n"]
for full, info in materials.items():
    short = full.split("/")[-1]
    c = cfg["shaders"].get(short)
    if c is None and short.endswith("_far"):   # backdrop copy: no collision, vertex lit (no lightmap pages)
        c = {k_: v_ for k_, v_ in dict(cfg["shaders"].get(short[:-4], {}), solid=False, vertexlit=True).items() if k_ != "raw"}
    c = c or {}
    tex = os.path.splitext(info["file"])[0]
    lines = [full, "{", f"\tqer_editorimage {info['file']}", f"\t// {c.get('what', '')}"]
    if c.get("raw"):          # hand-written stages (dust curtains): "{tex}" = this shader's texture
        sh.append("\n".join(lines + ["\t" + l.replace("{tex}", tex) for l in c["raw"]] + ["}\n"])); continue
    if c.get("fullbright"):   # sky dome / horizon cards: unlit, no collision, and light passes through them
        lines += ["\tsurfaceparm nonsolid", "\tsurfaceparm nolightmap", "\tsurfaceparm trans", "\tsurfaceparm nomarks",
                  "\tsurfaceparm noimpact"] + (["\tcull twosided"] if info["alpha"] else []) + [
                  "\t{", f"\t\tmap {tex}"] + (["\t\talphaFunc GE128"] if info["alpha"] else []) + ["\t\trgbGen identity", "\t}", "}\n"]
        sh.append("\n".join(lines)); continue
    if c.get("vertexlit"):     # far scenery: vertex lighting from q3map2, no lightmap
        lines += ["\tsurfaceparm nonsolid", "\tsurfaceparm nolightmap", "\tsurfaceparm nomarks", "\tq3map_nonplanar",
                  "\tq3map_shadeAngle 70"] + (["\tcull twosided"] if info["alpha"] or c.get("twosided") else []) + [
                  "\t{", f"\t\tmap {tex}"] + (["\t\talphaFunc GE128"] if info["alpha"] else []) + ["\t\trgbGen vertex", "\t}", "}\n"]
        sh.append("\n".join(lines)); continue
    if c.get("solid"):
        lines.append("\tq3map_clipModel")
    else:
        lines.append("\tsurfaceparm nonsolid")
    if c.get("mat"):
        lines.append(f"\tq3map_material {c['mat']}")
    lines += ["\tq3map_nonplanar", "\tq3map_shadeAngle 70"]
    if c.get("samplesize"):
        lines.append(f"\tq3map_lightmapSampleSize {c['samplesize']}")
    if (short.endswith("_d") or c.get("twosided")) and not info["alpha"]:
        lines.append("\tcull twosided")     # single-sided railings / signs of the rip: visible from behind too
    if info["alpha"]:
        lines += ["\tsurfaceparm alphashadow", "\tsurfaceparm trans", "\tcull twosided",
                  "\t{", f"\t\tmap {tex}", "\t\talphaFunc GE128", "\t\tdepthWrite", "\t\trgbGen identity", "\t}",
                  "\t{", "\t\tmap $lightmap", "\t\tblendFunc GL_DST_COLOR GL_ZERO", "\t\tdepthFunc equal",
                  "\t\trgbGen identity", "\t}"]
    else:
        lines += ["\t{", "\t\tmap $lightmap", "\t\trgbGen identity", "\t}",
                  "\t{", f"\t\tmap {tex}", "\t\tblendFunc GL_DST_COLOR GL_ZERO", "\t\trgbGen identity", "\t}"]
    lines.append("}\n")
    sh.append("\n".join(lines))
CLIP = ["surfaceparm nodraw", "surfaceparm nolightmap", "surfaceparm trans", "surfaceparm nonopaque"]
tool = {"caulk": ["surfaceparm nodraw", "surfaceparm nolightmap", "surfaceparm nomarks"],
        # players only (shots fly through): invisible walls / ceiling
        "playerclip": ["surfaceparm nodraw", "surfaceparm nolightmap", "surfaceparm trans", "surfaceparm nomarks",
                       "surfaceparm playerclip"]}
clip_mats = {"clip_rock": "rock", "clip_leaves": "greenleaves", **cfg.get("clip_shaders", {})}
for t, mat in clip_mats.items():
    tool[t] = CLIP + [f"q3map_material {mat}"]
for t, parms in tool.items():
    sh.append("\n".join([f"textures/{sd}/{t}", "{", "\tqer_trans 0.4", *[f"\t{p}" for p in parms], "}\n"]))
sky = cfg.get("sky")
if sky:
    sun = sky.get("sun"); sl = sky.get("skylight")
    sh.append("\n".join([f"textures/{sd}/sky", "{", f"\tqer_editorimage {sky['env']}_up",
        "\tsurfaceparm sky", "\tsurfaceparm noimpact", "\tsurfaceparm nomarks", "\tsurfaceparm nolightmap",
        *([f"\tq3map_sun {' '.join(map(str, sun))}"] if sun else []),
        *([f"\tq3map_skyLight {' '.join(map(str, sl))}"] if sl else []),
        f"\tskyParms {sky['env']} 512 -",
        *([] if not sky.get("clouds") else ["\t{", f"\t\tmap textures/{sd}/{sky['clouds']['texture']}",
          "\t\tblendFunc GL_SRC_ALPHA GL_ONE_MINUS_SRC_ALPHA", f"\t\ttcMod scale {sky['clouds'].get('scale', 3)} {sky['clouds'].get('scale', 3)}",
          f"\t\ttcMod scroll {' '.join(map(str, sky['clouds'].get('scroll', [0.004, 0.001])))}", "\t}"]), "}\n"]))
# shaders that are not on the model (map.json "extra_shaders": {short: {"gen": textures_gen kind, "raw": [...]}}),
# e.g. the water of a pool brush; "{tex}" = the generated texture
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
for short, c in cfg.get("extra_shaders", {}).items():
    tex = f"textures/{sd}/{short}"
    if c.get("gen"):
        import textures_gen
        ext = ".png" if c["gen"] in textures_gen.ALPHA else ".jpg"
        textures_gen.make(c["gen"], os.path.join(base, tex + ext))
        if ext == ".png":
            from PIL import Image
            Image.open(os.path.join(base, tex + ext)).save(os.path.join(base, tex + ".tga")); os.remove(os.path.join(base, tex + ext))
    ed = [] if any(l.startswith("qer_editorimage") for l in c["raw"]) else [f"\tqer_editorimage {tex}"]
    sh.append("\n".join([tex, "{", *ed, *["\t" + l.replace("{tex}", tex) for l in c["raw"]], "}\n"]))
open(os.path.join(base, "shaders", f"{name}.shader"), "w").write("\n".join(sh))

# --- .map ----------------------------------------------------------------------------------
def box(x0, y0, z0, x1, y1, z1, shader):
    s = f"{sd}/{shader} 0 0 0 0.5 0.5 0 0 0"   # .map faces name shaders without the textures/ prefix
    return "\n".join([
        "{",
        f"( {x0} 0 0 ) ( {x0} 1 0 ) ( {x0} 0 1 ) {s}",   # -X
        f"( {x1} 0 0 ) ( {x1} 0 1 ) ( {x1} 1 0 ) {s}",   # +X
        f"( 0 {y0} 0 ) ( 0 {y0} 1 ) ( 1 {y0} 0 ) {s}",   # -Y
        f"( 0 {y1} 0 ) ( 1 {y1} 0 ) ( 0 {y1} 1 ) {s}",   # +Y
        f"( 0 0 {z0} ) ( 1 0 {z0} ) ( 0 1 {z0} ) {s}",   # -Z
        f"( 0 0 {z1} ) ( 0 1 {z1} ) ( 1 0 {z1} ) {s}",   # +Z
        "}"])

def prism(poly, z0, z1, shader):
    """vertical prism over a convex polygon (counter-clockwise x, y points)"""
    s = f"{sd}/{shader} 0 0 0 0.5 0.5 0 0 0"
    f = lambda v: f"{v:.3f}".rstrip("0").rstrip(".")
    faces = [f"( 0 0 {f(z0)} ) ( 1 0 {f(z0)} ) ( 0 1 {f(z0)} ) {s}", f"( 0 0 {f(z1)} ) ( 0 1 {f(z1)} ) ( 1 0 {f(z1)} ) {s}"]
    for (ax, ay), (bx, by) in zip(poly, poly[1:] + poly[:1]):
        # points p0=a(z0), p1=a(z1), p2=b(z0): normal = (p2-p0) x (p1-p0) points outward for a ccw polygon
        faces.append(f"( {f(ax)} {f(ay)} {f(z0)} ) ( {f(ax)} {f(ay)} {f(z1)} ) ( {f(bx)} {f(by)} {f(z0)} ) {s}")
    return "{\n" + "\n".join(faces) + "\n}"

def plane_brush(planes, shader):
    """convex brush from outward planes [(normal, point on it), ...]"""
    import math
    s_ = f"{sd}/{shader} 0 0 0 0.5 0.5 0 0 0"
    out = []
    for n, q in planes:
        L = math.sqrt(sum(c * c for c in n)); n = [c / L for c in n]
        a = [0, 0, 1] if abs(n[2]) < 0.9 else [1, 0, 0]
        t1 = [n[1] * a[2] - n[2] * a[1], n[2] * a[0] - n[0] * a[2], n[0] * a[1] - n[1] * a[0]]
        L = math.sqrt(sum(c * c for c in t1)); t1 = [c / L for c in t1]
        t2 = [n[1] * t1[2] - n[2] * t1[1], n[2] * t1[0] - n[0] * t1[2], n[0] * t1[1] - n[1] * t1[0]]   # n x t1
        p0 = q; p2 = [q[k] + t1[k] * 64 for k in range(3)]; p1 = [q[k] + t2[k] * 64 for k in range(3)]
        out.append(" ".join("( " + " ".join(f"{v:.4f}" for v in p) + " )" for p in (p0, p1, p2)) + " " + s_)
    return "{\n" + "\n".join(out) + "\n}"

def slab(a, b, width, thick, shader):
    """flat or sloped walkway brush from a = [x, y, top z] to b, width across, thick below the top"""
    import math
    dx, dy = b[0] - a[0], b[1] - a[1]; L = math.hypot(dx, dy); ux, uy = dx / L, dy / L; px, py = -uy, ux
    dz = b[2] - a[2]; hw = width / 2
    top_n = [-dz * ux / L, -dz * uy / L, 1]                 # rises from a to b
    return plane_brush([(top_n, a), ([0, 0, -1], [a[0], a[1], min(a[2], b[2]) - thick]),
                        ([-ux, -uy, 0], a), ([ux, uy, 0], b),
                        ([px, py, 0], [a[0] + px * hw, a[1] + py * hw, 0]), ([-px, -py, 0], [a[0] - px * hw, a[1] - py * hw, 0])], shader)

def ent(kv, brushes=()):
    return "{\n" + "".join(f'"{k}" "{v}"\n' for k, v in kv.items()) + "".join(b + "\n" for b in brushes) + "}\n"

m = cfg.get("hull_margin", 32); t = 16
X0, Y0, Z0 = (int(v // 8 * 8) - m for v in mn)
X1, Y1, Z1 = (int(-(-v // 8) * 8) + m for v in mx)
hs = "sky" if sky else "caulk"   # open-air maps: the hull's top and sides are sky, the bottom caulk
hull = [box(X0 - t, Y0 - t, Z0 - t, X1 + t, Y1 + t, Z0, "caulk"), box(X0 - t, Y0 - t, Z1, X1 + t, Y1 + t, Z1 + t, hs),
        box(X0 - t, Y0 - t, Z0, X0, Y1 + t, Z1, hs), box(X1, Y0 - t, Z0, X1 + t, Y1 + t, Z1, hs),
        box(X0, Y0 - t, Z0, X1, Y0, Z1, hs), box(X0, Y1, Z0, X1, Y1 + t, Z1, hs)]
# invisible round boundary (map.json "boundary"): a ring of playerclip segments + a playerclip ceiling
bnd = cfg.get("boundary")
if bnd:
    import math
    cx, cy = bnd.get("center", [0, 0]); n = bnd.get("segments", 64); th = bnd.get("thickness", 32)
    z0, z1 = bnd.get("z0", -16), bnd["z1"]
    if "superellipse" in bnd:   # [a, b, exponent]: |x/a|^n + |y/b|^n = 1
        A, Bq, N = bnd["superellipse"]
        def curve(t):
            c, s_ = math.cos(t), math.sin(t)
            return (cx + A * math.copysign(abs(c) ** (2 / N), c), cy + Bq * math.copysign(abs(s_) ** (2 / N), s_))
    else:
        R = bnd["radius"]
        def curve(t):
            return (cx + R * math.cos(t), cy + R * math.sin(t))
    pts = [curve(2 * math.pi * i / n) for i in range(n)]
    def outward(i):   # vertex normal of the ccw polygon
        (ax, ay), (bx, by) = pts[i - 1], pts[(i + 1) % n]
        tx, ty = bx - ax, by - ay; L = math.hypot(tx, ty) or 1
        return ty / L, -tx / L
    for i in range(n):
        j = (i + 1) % n
        (ix, iy), (jx, jy) = pts[i], pts[j]
        (nix, niy), (njx, njy) = outward(i), outward(j)
        e = th * 1.6   # outer corners pushed further so neighbours overlap
        poly = [(ix, iy), (ix + nix * e, iy + niy * e), (jx + njx * e, jy + njy * e), (jx, jy)]
        hull.append(prism(poly, z0, z1, "playerclip"))   # inner i -> outer i -> outer j -> inner j = ccw
    xs_ = [p[0] for p in pts]; ys_ = [p[1] for p in pts]
    R = max(max(xs_) - cx, cx - min(xs_), max(ys_) - cy, cy - min(ys_))
    if "floor_z" in bnd:   # one flat floor brush instead of autoclipping a dense, nearly flat ground mesh
        e = int(R + th + 64)
        hull.append(box(cx - e, cy - e, bnd["floor_z"] - 32, cx + e, cy + e, bnd["floor_z"], "clip_floor"))
    if bnd.get("ceiling", True):
        e = int(R + th + 64)
        hull.append(box(cx - e, cy - e, z1, cx + e, cy + e, z1 + 16, "playerclip"))
props = []
for g in json.load(open(os.path.join(build, "propclip.json"))):
    props += [box(*b, g["shader"]) for b in g["boxes"]]
    props += [prism([tuple(v) for v in pr["poly"]], pr["z0"], pr["z1"], g["shader"]) for pr in g.get("prisms", [])]

# walkway clip (map.json "slabs": [{"from": [x, y, z], "to": [x, y, z], "width", "thick", "shader"}]): a smooth
# floor over a bumpy deck whose own collision was dropped (split_details "regions")
stairs_json = os.path.join(build, "stairs.json")   # tools/maps/stairs.py: one smooth ramp per staircase
stair_ramps = json.load(open(stairs_json)) if cfg.get("stairs") and os.path.exists(stairs_json) else []
if os.path.exists(os.path.join(build, "slabs.json")):    # bridge decks etc. from props.py
    stair_ramps += json.load(open(os.path.join(build, "slabs.json")))
for sl in [s_ for s_ in cfg.get("slabs", []) if "from" in s_] + stair_ramps:
    props.append(slab(sl["from"], sl["to"], sl.get("width", 96), sl.get("thick", 24), sl.get("shader", "clip_floor")))
# water volumes (map.json "water": [{"box": [x0, y0, z0, x1, y1, z1], "shader": short}])
wfiles = [json.load(open(os.path.join(build, f))) for f in ("water.json", "waterfill.json") if os.path.exists(os.path.join(build, f))]
for wv in cfg.get("water", []) + [w_ for wl in wfiles for w_ in wl]:
    if "box" in wv:
        props.append(box(*wv["box"], wv.get("shader", "water")))
    elif "poly" in wv:                       # convex ccw polygon (streams, ponds)
        props.append(prism([tuple(q) for q in wv["poly"]], wv["z0"], wv["z1"], wv.get("shader", "water")))

ws = {"classname": "worldspawn", "message": cfg["longname"], **cfg.get("worldspawn", {})}
out = [ent(ws, hull + props)]
# spawnflags 4 = force meta: cut the model into lightmappable meta surfaces (JA: <= 64 verts each)
out.append(ent({"classname": "misc_model", "model": mdl_rel, "origin": "0 0 0", "spawnflags": "4", "_clipdepth": "8",
                "_castshadows": "1", "_receiveshadows": "1", "_lightmapscale": ws.get("_lightmapscale", "1")}))
L = cfg.get("lights", {"grid_x": [], "grid_y": []})
for x in L.get("grid_x", []):
    for y in L.get("grid_y", []):
        out.append(ent({"classname": "light", "origin": f"{x} {y} {L['z']}", "light": str(L["light"])}))
room_lights = os.path.join(build, "room_lights.json")      # prep_model "rooms": a light per indoor room
for e in L.get("extra", []) + (json.load(open(room_lights)) if cfg.get("rooms") and os.path.exists(room_lights) else []):
    out.append(ent({"classname": "light", "origin": " ".join(map(str, e["origin"])), "light": str(e["light"]),
                    **({"_color": " ".join(map(str, e["color"]))} if "color" in e else {})}))
for cls, pts in cfg["spawns"].items():
    if cls.startswith("_"):
        continue
    for x, y, z, yaw in pts:
        out.append(ent({"classname": cls, "origin": f"{x} {y} {z}", "angle": str(yaw)}))
# pickups (map.json "items": [{"class": ..., "at": [x, y, z]}]): stock classnames, the mod turns them into
# ninja items at load (codemp/game/bg_shinobi.c shinobiItemMap). They drop to the floor below "at".
for it in cfg.get("items", []):
    if "class" in it:
        out.append(ent({"classname": it["class"], "origin": " ".join(map(str, it["at"]))}))
open(os.path.join(base, "maps", f"{name}.map"), "w").write("// generated by tools/maps/gen_map.py\n" + "".join(out))

# --- arena ---------------------------------------------------------------------------------
open(os.path.join(base, "scripts", f"{name}.arena"), "w").write(
    "{\n" + f'map "{name}"\nlongname "{cfg["longname"]}"\ntype "{cfg["arena_type"]}"\n' + "}\n")

print(f"GEN OK {name}: hull {X0},{Y0},{Z0} .. {X1},{Y1},{Z1}; {len(props)} prop clip brushes; "
      f"{len(materials)} model shaders; {len(L.get('grid_x', [])) * len(L.get('grid_y', [])) + len(L.get('extra', []))} lights"
      + (f"; sky {sky['env']}" if sky else "") + (f"; boundary {bnd.get('superellipse') or bnd.get('radius')}" if bnd else "")
      + f"; {sum('class' in it for it in cfg.get('items', []))} items")
